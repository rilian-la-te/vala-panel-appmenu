#include "appmenu-gtk-parser.h"
#include "comparator.h"
#include <gtk/gtk.h>

static GMenuModel *build_source_model(void)
{
	GMenu *menu = g_menu_new();

	/* Section 1: plain items. */
	{
		GMenu *s = g_menu_new();
		g_menu_append(s, "New", "app.new");
		g_menu_append(s, "Open", "app.open");
		g_menu_append(s, "Save", "app.save");
		g_menu_append_section(menu, NULL, G_MENU_MODEL(s));
		g_object_unref(s);
	}

	/* Section 2: submenu + a plain item. */
	{
		GMenu *s      = g_menu_new();
		GMenu *recent = g_menu_new();
		g_menu_append(recent, "Recent 1", "app.recent1");
		g_menu_append(recent, "Recent 2", "app.recent2");
		g_menu_append_submenu(s, "Recent", G_MENU_MODEL(recent));
		g_object_unref(recent);
		g_menu_append(s, "Quit", "app.quit");
		g_menu_append_section(menu, NULL, G_MENU_MODEL(s));
		g_object_unref(s);
	}

	/* Section 3: a single item. */
	{
		GMenu *s = g_menu_new();
		g_menu_append(s, "Help", "app.help");
		g_menu_append_section(menu, NULL, G_MENU_MODEL(s));
		g_object_unref(s);
	}

	return G_MENU_MODEL(menu);
}

/* ------------------------------------------------------------------ */

int main(int argc, char *argv[])
{
	if (!gtk_init_check(&argc, &argv))
	{
		g_printerr("Skipping: no display available\n");
		return 77; /* Meson: skipped */
	}

	GMenuModel *source = build_source_model();

	GtkWidget *menubar = gtk_menu_bar_new();
	gtk_menu_shell_bind_model(GTK_MENU_SHELL(menubar), source, NULL, TRUE);

	/* Parse GtkMenuShell back into a GMenuModel. */
	UnityGtkMenuShell *shell = unity_gtk_menu_shell_new(GTK_MENU_SHELL(menubar));

	/* The parser only emits action attributes for items that have a
	 * UnityGtkAction attached, so an action group must be created and
	 * connected before querying the model. */
	UnityGtkActionGroup *action_group = unity_gtk_action_group_new(NULL);
	unity_gtk_action_group_connect_shell(action_group, shell);

#ifdef NO_LAZY
	(void)g_menu_model_get_n_items(G_MENU_MODEL(shell));
#endif

	GString *errors = g_string_new(NULL);

	/* Comparison "in essence". Actions are generated by the parser in the
	 * "unity.*" namespace, so they are not compared against the source's
	 * "app.*" actions. Instead we verify that the parser produced at least
	 * one action — this catches the previous bug where the action group
	 * was never wired up. */
	gboolean ok = compare_models(source, G_MENU_MODEL(shell), errors, 0);

	gboolean has_actions = FALSE;
	check_any_actions(G_MENU_MODEL(shell), &has_actions);
	if (!has_actions)
	{
		g_string_append(errors,
		                "parsed model contains no 'unity.*' action attributes; "
		                "the action group was not wired\n");
		ok = FALSE;
	}

	if (!ok)
	{
		g_printerr("Models differ:\n%s\n", errors->str);
		g_printerr("--- source ---\n");
		g_menu_markup_print_to_console(source);
		g_printerr("--- parsed ---\n");
		g_menu_markup_print_to_console(G_MENU_MODEL(shell));
	}

	g_string_free(errors, TRUE);
	g_object_unref(shell);
	g_object_unref(action_group);
	gtk_widget_destroy(menubar);
	g_object_unref(source);

	return ok ? 0 : 1;
}
